#!/usr/bin/env bash
# Sets up build-time Fabric for an Eaglercraft 26.2 workspace.
#   loader/weave.sh WORKSPACE_DIR WORK_DIR
#
# Afterwards, any Gradle build of the workspace weaves the mods in mods/ into the game right after
# :game:compileJava (through an init script in ~/.gradle/init.d), so every browser target (client,
# singleplayer server worker, mesh worker) is compiled from the modded classes:
#   1. Fabric Loader (at build time) applies class tweakers, access wideners and mixins to the game
#      and to the mods (loader/weaver)
#   2. the browser side of Fabric Loader (loader/runtime) and the list of mods and entrypoints
#      (generated by loader/gen-runtime.py) are compiled in next to them
# The mods' assets/ and data/ are merged into the game's resources here (loader/merge-assets.py).
# Needs Java 25 on PATH and network access to maven.fabricmc.net.
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
WS="$(cd "$1" && pwd)"
WORK="$(mkdir -p "$2" && cd "$2" && pwd)"

echo "::group::Fabric Loader and the weaver"
LOADER_VERSION="$(python3 "$REPO/loader/fetch-deps.py" "$WORK/deps" "${FABRIC_LOADER_VERSION:-}")"
echo "Fabric Loader $LOADER_VERSION"
DEPS="$(ls "$WORK"/deps/*.jar | tr '\n' ':')"
LOADER_JAR="$(ls "$WORK"/deps/fabric-loader-*.jar | head -1)"
MIXIN_JAR="$(ls "$WORK"/deps/sponge-mixin-*.jar | head -1)"
rm -rf "$WORK/weaver"; mkdir -p "$WORK/weaver"
javac --release 21 -nowarn -cp "$DEPS" -d "$WORK/weaver" $(find "$REPO/loader/weaver/src" -name '*.java')
cp -r "$REPO/loader/weaver/resources/." "$WORK/weaver/"
echo "::endgroup::"

echo "::group::Mods"
RUN="$WORK/run"; rm -rf "$RUN" "$RUN-patched" "$WORK/disabled-injectors.txt"; mkdir -p "$RUN/mods" "$RUN/config"
cp "$REPO"/mods/*.jar "$RUN/mods/" 2>/dev/null || true
# the built-in "eaglermodloader" mod: mixins that start the mods' entrypoints
IM="$WORK/internal-mod"; rm -rf "$IM"; mkdir -p "$IM/classes" "$IM/stub/eaglermodloader/runtime"
cat > "$IM/stub/eaglermodloader/runtime/GeneratedMods.java" <<'EOF'
package eaglermodloader.runtime;
public final class GeneratedMods {
	public static final String LOADER_VERSION = "", GAME_VERSION = "";
	public static final String[][] MODS = {};
	public static java.util.List<EmlEntrypoint> entrypoints(String key) { return java.util.Collections.emptyList(); }
	public static void enableClient() { }
	public static void freezeRegistries() { }
	public static byte[] resource(String path) { return null; }
	public static void afterClientStart() { }
	public static void beforeBusyScreenTick(Object minecraft) { }
	public static java.lang.reflect.Type genericFieldType(String key) { return null; }
}
EOF
javac --release 21 -nowarn -proc:none -cp "$DEPS" -d "$IM/classes" \
  $(find "$REPO/loader/internal-mod/src" "$REPO/loader/runtime/src" "$IM/stub" -name '*.java') \
  "$REPO/loader/teavm-compat/java/net/lax1dude/eaglercraft/v1_8/teavmcompat/EmlGenericTypes.java"
(cd "$IM/classes" && rm -rf net eaglermodloader/runtime && cp -r "$REPO/loader/internal-mod/resources/." . && jar --create --file "$RUN/mods/eaglermodloader.jar" .)
ls -la "$RUN/mods"
python3 "$REPO/loader/merge-assets.py" "$WS/game/src/main/resources" "$RUN"/mods/*.jar
echo "::endgroup::"

# The singleplayer server worker is linked from a slice of game.jar that the workspace puts last on
# its classpath. Library classes the mods changed (DataFixerUpper's TaggedChoice, ...) are in that
# slice, so it has to come first, as game.jar does for the client, or the originals win.
python3 - "$WS/target_teavm_wasm_gc_server/build.gradle.kts" <<'EOF'
import sys
p = sys.argv[1]; s = open(p).read()
old = """	val slicedClasspath = standardWasmGCTask.classpath.files
		.filter { it.name != "game.jar" }
		.plus(File(eaglerServerGameJar))"""
new = """	val slicedClasspath = listOf(File(eaglerServerGameJar)) + standardWasmGCTask.classpath.files
		.filter { it.name != "game.jar" }"""
if new not in s:
    if old not in s: sys.exit("eagler-modloader: could not put the server's game classes first in " + p)
    open(p, "w").write(s.replace(old, new))
print("server worker: game classes first on the classpath")
EOF

# Minecraft opens links (chat links, Mod Menu's Website/Issues buttons, ...) with Util.OS.openUri,
# which in Eaglercraft is still the desktop version (it runs xdg-open). Open web links in a new tab.
python3 - "$WS/game/src/main/java/net/minecraft/util/Util.java" <<'EOF'
import sys
p = sys.argv[1]; s = open(p).read()
old = "      public void openUri(final URI uri) {\n         try {\n            Process process"
new = """      public void openUri(final URI uri) {
         String scheme = uri.getScheme() == null ? "" : uri.getScheme().toLowerCase(java.util.Locale.ROOT);
         if (scheme.equals("http") || scheme.equals("https") || scheme.equals("mailto")) {
            net.lax1dude.eaglercraft.v1_8.EagRuntime.openLink(uri.toString());
            return;
         }
         try {
            Process process"""
if new in s:
    print("links: already open in the browser")
elif old in s:
    open(p, "w").write(s.replace(old, new, 1))
    print("links: open in a new browser tab")
else:
    sys.exit("eagler-modloader: Util.OS.openUri changed; check the link fix")
EOF

# Mods that read and write fields by reflection (Mod Menu's settings, config libraries): the browser
# compiler keeps field readers/writers only for fields a ReflectionSupplier names. This one names every
# field of the classes the weave found mods reflecting on (eml-reflect.txt in the game classes).
TC="$WS/teavm-compat/src/main"
# the loader's additions to Eaglercraft's TeaVM layer (loader/teavm-compat): java.awt.Color for mods
# that do colour maths with it, the reflection supplier, Log4j's API, OSHI's tuples and a ServiceLoader donor
cp -r "$REPO/loader/teavm-compat/java/." "$TC/java/"
SVC="$TC/resources/META-INF/services/org.teavm.classlib.ReflectionSupplier"
grep -qs EmlReflectionSupplier "$SVC" || cat "$REPO/loader/teavm-compat/resources/META-INF/services/org.teavm.classlib.ReflectionSupplier.eml" >> "$SVC"
echo "teavm-compat: java.awt.Color and the reflection supplier added"

# Missing pieces some mods use (more of loader/teavm-compat): Log4j's logging API, OSHI's tuples,
# ServiceLoader.findFirst() (a donor for Eaglercraft's JdkMethodInjector) and glfwGetMouseButton.
# A mod may also use a class or method the browser doesn't have at all (a desktop library, a newer JDK
# method). TeaVM compiles that spot to throw NoClassDefFoundError/NoSuchMethodError when it runs and
# reports it as an error; Eaglercraft's linker stops on any error, so only those are let through.
python3 "$REPO/loader/patch-workspace.py" "$WS"

# Eaglercraft's java.lang.ScopedValue records which values were bound only after binding them, so
# every value used once stays "bound" (to null) afterwards. Fabric API's registry sync then reads
# null from IS_SERVER.orElse(false) when joining a world. Record the states first.
python3 - "$WS/teavm-compat/src/main/java/net/lax1dude/eaglercraft/v1_8/teavmcompat/java/lang/TScopedValue.java" <<'EOF'
import sys
p = sys.argv[1]; s = open(p).read()
old = "Object[] savedValues = bind();\n\t\t\tboolean[] savedBound = savedBoundStates();"
new = "boolean[] savedBound = savedBoundStates();\n\t\t\tObject[] savedValues = bind();"
if old in s:
    open(p, "w").write(s.replace(old, new))
    print("ScopedValue: fixed restoring bound states")
elif new in s:
    print("ScopedValue: already fixed")
else:
    sys.exit("eagler-modloader: TScopedValue.java changed; check the bound-state fix")
EOF

mkdir -p "$HOME/.gradle/init.d"
cat > "$HOME/.gradle/init.d/eagler-modloader.gradle" <<EOF
// eagler-modloader: weave Fabric mods into :game right after it compiles.
allprojects {
  afterEvaluate { p ->
    if (p.path != ":game") return
    p.tasks.named("compileJava").configure { t ->
      t.outputs.upToDateWhen { false }
      t.doLast {
        def classes = t.destinationDirectory.get().asFile
        def out = new File("$WORK/woven")
        out.deleteDir()
        def cp = p.sourceSets.main.compileClasspath.files.collect { it.absolutePath }.join(File.pathSeparator)
        def run = { List<String> cmd, String logName, List<Integer> okCodes = [0] ->
          def res = p.providers.exec { commandLine cmd; ignoreExitValue = true }
          def log = res.standardOutput.asText.get() + res.standardError.asText.get()
          new File("$WORK/" + logName).text = log
          println(log.readLines().findAll { it.startsWith("[weave]") || it.startsWith("[gen]") || it.startsWith("[compat]") || it.contains("/ERROR]") || it.contains("error:") || it.contains("Caused by") }.take(400).join("\n"))
          int code = res.result.get().exitValue
          if (!okCodes.contains(code)) throw new GradleException("eagler-modloader: " + logName + " failed (see $WORK/" + logName + ")")
          return code
        }
        // 1. weave; injectors that don't fit Eaglercraft are turned off one round at a time (exit code 3)
        int round = 0
        while (true) {
          round++
          int code = run(["java", "-Xmx6g",
            "-Deml.gameJar=" + classes.absolutePath, "-Deml.gameLibs=" + cp, "-Deml.runDir=$RUN",
            "-Deml.disableFile=$WORK/disabled-injectors.txt", "-Dfabric.gameVersion=26.2", "-Dmixin.debug.export=true",
            "-cp", "$WORK/weaver" + File.pathSeparator + "$DEPS", "eaglermodloader.weaver.Weave", out.absolutePath], "weave.log", [0, 3])
          if (code == 0) break
          if (round >= 12) throw new GradleException("eagler-modloader: weaving did not settle after 12 rounds")
        }
        p.copy { from new File(out, "classes"); into classes }
        // 2. the loader API, the Mixin callback classes and our browser loader
        p.copy {
          from(p.zipTree("$LOADER_JAR")) { include "net/fabricmc/**"; exclude "net/fabricmc/loader/impl/FabricLoaderImpl*.class" }
          from(p.zipTree("$MIXIN_JAR")) { include "org/spongepowered/asm/mixin/injection/callback/**" }
          into classes
          duplicatesStrategy = DuplicatesStrategy.EXCLUDE
        }
        // 3. switch off code that can't work in a browser (loader/browser-compat.txt)
        run(["java", "-cp", "$WORK/weaver" + File.pathSeparator + "$DEPS", "eaglermodloader.weaver.Weave",
          "--browser-compat", classes.absolutePath, "$REPO/loader/browser-compat.txt"], "compat.log")
        // 4. the list of mods and entrypoints, and the browser side of Fabric Loader
        run(["python3", "$REPO/loader/gen-runtime.py", new File(out, "mods.json").absolutePath, classes.absolutePath,
          "$LOADER_VERSION", "$WORK/gen/eaglermodloader/runtime/GeneratedMods.java"], "gen.log")
        def srcs = []
        new File("$REPO/loader/runtime/src").eachFileRecurse { if (it.name.endsWith(".java")) srcs << it.absolutePath }
        srcs << "$WORK/gen/eaglermodloader/runtime/GeneratedMods.java"
        // compiled against, but the browser uses teavm-compat's copy (see EmlGenericTypes)
        srcs << "$REPO/loader/teavm-compat/java/net/lax1dude/eaglercraft/v1_8/teavmcompat/EmlGenericTypes.java"
        run(["javac", "--release", "24", "-nowarn", "-proc:none",
          "-cp", classes.absolutePath + File.pathSeparator + cp, "-d", classes.absolutePath] + srcs, "runtime-javac.log")
        new File(classes, "net/lax1dude/eaglercraft/v1_8/teavmcompat/EmlGenericTypes.class").delete()
        println("[eagler-modloader] mods woven into " + classes)
      }
    }
  }
}
EOF
echo "init script installed: $HOME/.gradle/init.d/eagler-modloader.gradle"
